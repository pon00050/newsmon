"""Generate THIRD_PARTY_NOTICES.md from the runtime dependency closure, and check it for licences that would conflict
with distributing Newsmon under Apache-2.0.

    uv run python scripts/third_party_notices.py            # rewrite THIRD_PARTY_NOTICES.md
    uv run python scripts/third_party_notices.py --check    # exit 1 if the file is stale or a licence is not allowed

The closure comes from `uv export --no-dev` (the lock file), the licence of each package from its installed metadata
(License-Expression, then License, then trove classifiers). Run it in an environment synced with `uv sync --frozen`.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
# Permissive or weak-copyleft (file-level) licences compatible with redistributing Newsmon under Apache-2.0.
ALLOWED = re.compile(r"\b(MIT|BSD|Apache|ISC|PSF|PSFL|Python Software Foundation|MPL|Mozilla Public License 2\.0|"
                     r"Unlicense|CC0|Zlib|HPND|0BSD|Historical Permission)\b", re.I)
DENIED = re.compile(r"\b(AGPL|(?<!L)GPL|SSPL|Commons Clause|BUSL|Business Source)\b", re.I)


def _marker_applies(marker: str) -> bool:
    try:
        from packaging.markers import Marker
    except ImportError:
        return True
    return Marker(marker.strip()).evaluate() or Marker(marker.strip()).evaluate({"sys_platform": "linux",
                                                                                   "platform_system": "Linux"})


def closure() -> list[tuple[str, str]]:
    out = subprocess.run(["uv", "export", "--frozen", "--no-dev", "--no-hashes", "--no-emit-project",
                          "--format", "requirements-txt"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    pkgs = []
    for line in out.splitlines():
        line, _, marker = line.partition(";")
        line = line.strip()
        if marker.strip() and not _marker_applies(marker):  # e.g. a package only used on emscripten
            continue
        if line and not line.startswith(("#", "-")) and "==" in line:
            name, ver = line.split("==", 1)
            pkgs.append((name.strip(), ver.strip()))
    return sorted(set(pkgs), key=lambda p: p[0].lower())


def licence_of(name: str) -> tuple[str, str]:
    try:
        md = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "NOT INSTALLED", ""
    expr = md.get("License-Expression")
    lic = (md.get("License") or "").strip()
    classifiers = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    if expr:
        value = expr
    elif lic and len(lic) < 80 and "\n" not in lic:
        value = lic
    elif classifiers:
        value = "; ".join(classifiers)
    else:
        value = (lic.splitlines() or ["UNKNOWN"])[0][:80]
    url = md.get("Home-page") or next((u.split(",", 1)[1].strip() for u in md.get_all("Project-URL") or []
                                       if "," in u), "")
    return value, url


def render() -> tuple[str, list[str]]:
    rows, problems = [], []
    for name, ver in closure():
        lic, url = licence_of(name)
        if DENIED.search(lic) or not ALLOWED.search(lic):
            problems.append(f"{name} {ver}: {lic}")
        rows.append(f"| {name} | {ver} | {lic} | {url} |")
    text = "\n".join([
        "# Third-party notices",
        "",
        "Newsmon is licensed under Apache-2.0 (`LICENSE`). It depends on the open-source packages below, which are",
        "installed from PyPI by `uv sync` and keep their own licences. The Windows portable build bundles these packages",
        "and a CPython runtime (PSF License); each package's licence file is included in the bundle's metadata folders.",
        "",
        "Generated by `scripts/third_party_notices.py` from `uv.lock` and the packages' own metadata. Do not edit.",
        "",
        "| Package | Version | Licence (from package metadata) | Project |",
        "|---|---|---|---|",
        *rows,
        "",
        "Notes",
        "",
        "- `certifi` is MPL-2.0: redistributing it unmodified is permitted; its source is available from PyPI.",
        "- No runtime dependency is under GPL, AGPL or another licence that would require Newsmon to change its own.",
        "- Research documents and the synthetic demo data are licensed CC BY 4.0 (`LICENSE-CC-BY-4.0.txt`). Third-party",
        "  news content is not redistributed; the research cites and links to it.",
        "",
    ])
    return text, problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text, problems = render()
    for p in problems:
        print(f"licence not on the allowed list: {p}", file=sys.stderr)
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("THIRD_PARTY_NOTICES.md is stale: run scripts/third_party_notices.py", file=sys.stderr)
            return 1
        return 1 if problems else 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {text.count(chr(10) + '| ') - 1} packages, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
