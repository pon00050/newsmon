"""Prove requirement coverage from a junit report (T-04, test plan §1.7).

Each test carries `@pytest.mark.req("<id>")`; conftest copies the ids into junit `<property name="req" value=...>`.
A requirement counts as covered only if at least one test carrying it PASSED (not skipped, failed or errored) and no
test carrying it failed.

  python tools/req_coverage.py reports/junit.xml --require release_a
  python tools/req_coverage.py reports/junit.xml --require o1
  python tools/req_coverage.py reports/junit.xml --ids FR-05a,FR-05b
  python tools/req_coverage.py --build-ids     # regenerate tests/requirement_ids.txt from the catalogue

Exit 0 when every required id is covered, 1 otherwise (missing ids are printed), 2 on usage errors.
"""
from __future__ import annotations

import argparse
import csv
import sys
import xml.etree.ElementTree as ET  # parses our own pytest output only
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IDS_FILE = ROOT / "tests" / "requirement_ids.txt"
CATALOGUE = ROOT / "tests" / "test_catalogue.csv"

# Release A acceptance criteria (DECISION_LOG P-011; user message 2026-11-25 §9).
RELEASE_A = {
    "RA-01": "installs in the project environment",
    "RA-02": "starts without AI credentials",
    "RA-03": "offline fixture-based end-to-end test passes",
    "RA-04": "authorised RSS feeds are collected",
    "RA-05": "representative local files are ingested",
    "RA-06": "records persist across restarts",
    "RA-07": "repeated ingestion creates no unintended duplicates",
    "RA-08": "configurable ranking rules change the queue",
    "RA-09": "search returns the expected records",
    "RA-10": "source storage and display restrictions are enforced",
    "RA-11": "a failed or malformed source does not halt other collection",
    "RA-12": "the local web UI shows collected records",
    "RA-13": "regression and architecture tests pass",
    "RA-14": "started and operated with documented commands",
    "RA-15": "repeated-collection reliability",
}


# Criteria proven by a command's exit status rather than by a test that carries the id (a test cannot honestly assert
# that the whole suite it belongs to is green). tools/progress.py runs these commands.
PROVEN_BY_COMMAND = {"RA-13": 'uv run pytest -q -m "not live and not slow" (includes tests/arch)'}


def build_ids() -> str:
    groups: dict[str, set[str]] = defaultdict(set)
    tests: dict[str, set[str]] = defaultdict(set)
    with open(CATALOGUE, encoding="utf-8-sig") as fh:
        for row in csv.DictReader(fh):
            for rid in row["covers"].split():
                tests[rid].add(row["test_id"])
                mode = row["mode"]
                groups[rid].add({"O1": "o1", "n/a": "o1", "AI-stub": "ai", "live": "live"}.get(mode, mode))
    for rid in RELEASE_A:
        if rid not in PROVEN_BY_COMMAND:
            groups[rid].add("release_a")
    lines = ["# Generated by tools/req_coverage.py --build-ids from 08_testing/test_catalogue.csv + Release A (P-011).",
             "# id<TAB>groups<TAB>catalogue tests"]
    for rid in sorted(groups):
        lines.append(f"{rid}\t{','.join(sorted(groups[rid]))}\t{' '.join(sorted(tests.get(rid, ())))}")
    return "\n".join(lines) + "\n"


def load_groups(path: Path = IDS_FILE) -> dict[str, set[str]]:
    out: dict[str, set[str]] = defaultdict(set)
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        rid, grp = line.split("\t")[:2]
        for g in grp.split(","):
            out[g].add(rid)
    return out


def coverage(junit: Path) -> tuple[set[str], set[str]]:
    """Return (passed_ids, failed_ids) from a junit xml file."""
    passed, failed = set(), set()
    root = ET.parse(junit).getroot()
    for case in root.iter("testcase"):
        ids = {p.get("value") for p in case.iter("property") if p.get("name") == "req"}
        if not ids:
            continue
        outcome = "passed"
        for child in case:
            if child.tag in ("failure", "error"):
                outcome = "failed"
            elif child.tag == "skipped" and outcome == "passed":
                outcome = "skipped"
        if outcome == "passed":
            passed |= ids
        elif outcome == "failed":
            failed |= ids
    return passed, failed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("junit", nargs="?", type=Path)
    ap.add_argument("--require", help="group name from tests/requirement_ids.txt (o1, ai, live, release_a)")
    ap.add_argument("--ids", help="comma-separated ids to require")
    ap.add_argument("--ids-file", type=Path, default=IDS_FILE)
    ap.add_argument("--build-ids", action="store_true")
    a = ap.parse_args(argv)
    if a.build_ids:
        IDS_FILE.write_text(build_ids(), encoding="utf-8", newline="\n")
        print(f"wrote {IDS_FILE}")
        return 0
    if not a.junit or not (a.require or a.ids):
        ap.print_usage(sys.stderr)
        return 2
    required: set[str] = set()
    if a.require:
        groups = load_groups(a.ids_file)
        if a.require not in groups:
            print(f"unknown group {a.require!r}; known: {', '.join(sorted(groups))}", file=sys.stderr)
            return 2
        required |= groups[a.require]
    if a.ids:
        required |= {x.strip() for x in a.ids.split(",") if x.strip()}
    passed, failed = coverage(a.junit)
    covered = (passed - failed) & required
    missing = sorted(required - covered)
    print(f"requirements covered: {len(covered)}/{len(required)}")
    for rid in missing:
        why = "FAILED" if rid in failed else "no passing test"
        print(f"  MISSING {rid}: {why}")
    return 0 if not missing else 1


if __name__ == "__main__":
    sys.exit(main())
